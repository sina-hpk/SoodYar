/** Renders one glossary/teaching entry: title, body, steps, formulas, note, table. */
function TermBlock({ term: t }: { term: GlossarySection["terms"][number] }) {
  return (
    <div>
      <div className="flex flex-wrap items-center gap-2">
        {t.tag && (
          <span className="rounded-md bg-brand-50 px-2 py-0.5 text-xs font-medium text-brand-700">
            {t.tag}
          </span>
        )}
        <span className="font-semibold text-slate-800">{t.term}</span>
      </div>
      <p className="mt-1 text-sm leading-7 text-slate-600">{t.body}</p>
      {t.steps && (
        <ol className="mt-2 space-y-1.5 pr-1 text-sm leading-7 text-slate-600">
          {t.steps.map((s, i) => (
            <li key={i} className="flex gap-2">
              <span className="mt-2 h-1.5 w-1.5 flex-shrink-0 rounded-full bg-brand-400" />
              <span>{s}</span>
            </li>
          ))}
        </ol>
      )}
      {t.formula && <Formulas specs={t.formula} />}
      {t.table && (
        <div className="mt-2 overflow-x-auto">
          <table className="w-full text-sm">
            <thead>
              <tr className="border-b border-slate-100">
                {t.table.head.map((h) => (
                  <th key={h} className="th whitespace-nowrap">
                    {h}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {t.table.rows.map((row, i) => (
                <tr key={i} className="border-b border-slate-50 last:border-0">
                  {row.map((cell, j) => (
                    <td
                      key={j}
                      className={`td whitespace-nowrap ${j === 0 ? "text-slate-700" : "tabular text-slate-600"}`}
                    >
                      {cell}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
      {t.note && (
        <p className="mt-2 rounded-lg border-r-4 border-amber-300 bg-amber-50/70 px-3 py-2 text-sm leading-7 text-amber-900">
          {t.note}
        </p>
      )}
    </div>
  );
}

