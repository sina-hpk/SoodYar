/**
 * Teaching content for the Help & Glossary page.
 *
 * The year-long story is a single consistent ledger: every event is calculated
 * from the state the previous event left behind, so a newcomer can follow the
 * numbers all the way from an empty fund to the end-of-year report. Amounts are
 * in toman (the app stores rial) and are rounded for readability.
 */

/** One glossary entry: a term, its plain-Persian explanation, and optional extras. */
export interface GlossaryTerm {
  term: string;
  body: string;
  /** Small chip before the title — used for the date in the year-long story. */
  tag?: string;
  steps?: string[];
  formula?: FormulaSpec | FormulaSpec[];
  /** Highlighted takeaway, shown after the formulas. */
  note?: string;
  /** A compact state table, e.g. the fund right after one event. */
  table?: { head: string[]; rows: string[][] };
}

export interface GlossarySection {
  title: string;
  /** Optional lead-in paragraph shown under the section title. */
  intro?: string;
  terms: GlossaryTerm[];
}

